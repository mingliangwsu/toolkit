# Cell 6 — update / copy CS_rotation files, handling both single-crop
# and two-crop (two [sowing:N] sections) rotation files

import os
import re
import glob
import shutil
import datetime

# --- dates from the state file ---
branch_date  = pd.to_datetime(df["date"].iloc[0]).date()      # e.g. 1985-07-10
state_doy    = branch_date.timetuple().tm_yday                # e.g. 191 -- used for the decision logic
restart_date = branch_date + datetime.timedelta(days=1)
restart_doy_str = f"{restart_date.timetuple().tm_yday:04d}"   # e.g. "0192" -- the value we write in
print(f"branch_date={branch_date}  state_doy={state_doy}  restart_doy={restart_doy_str}")

JULY1_DOY = 182  # non-leap-year day-of-year for July 1, consistent with the rest of the pipeline

def find_sowing_sections(content):
    """Split a .CS_rotation file into its [sowing:N] blocks."""
    matches = list(re.finditer(r"\[sowing:(\d+)\]", content))
    sections = []
    for i, m in enumerate(matches):
        start = m.start()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(content)
        sections.append({"num": int(m.group(1)), "start": start, "end": end, "text": content[start:end]})
    return sections

def section_date(section_text):
    m = re.search(r"^date=(\d+)", section_text, re.MULTILINE)
    return int(m.group(1)) if m else None

def replace_section_dates(section_text, new_doy_str):
    """Update both event_date= and date= within a single section's text."""
    text = re.sub(r"^event_date=\d+", f"event_date={new_doy_str}", section_text, flags=re.MULTILINE)
    text = re.sub(r"^date=\d+", f"date={new_doy_str}", text, flags=re.MULTILINE)
    return text

def choose_section_to_update(sections, state_doy):
    """Decide which [sowing:N] section is the one that's currently growing."""
    if len(sections) == 1:
        return sections[0]["num"]
    if len(sections) != 2:
        return None  # only 1- and 2-crop rotations are handled by these rules

    first, second = sorted(sections, key=lambda s: s["num"])
    first_doy, second_doy = section_date(first["text"]), section_date(second["text"])

    if first_doy < JULY1_DOY:
        # both crops sown within the same calendar-year window
        if first_doy <= state_doy <= second_doy:
            return first["num"]
        elif state_doy > second_doy or state_doy < first_doy: #might be next year before first crop sow
            return second["num"]
        else:
            return None  #needs manual review
    elif first_doy >= JULY1_DOY and second_doy < JULY1_DOY:
        # rotation spans a calendar-year boundary (e.g. fall-sown -> spring-sown)
        if state_doy >= first_doy or state_doy <= second_doy:
            return first["num"]
        elif second_doy <= state_doy <= first_doy:
            return second["num"]
        else:
            return None
    else:
        return None  # configuration not covered by the given rules

for src_path in glob.glob(os.path.join(ORIG_ROTATION_PATH, "*.CS_rotation")):
    fname = os.path.basename(src_path)
    code = fname[: -len(".CS_rotation")]
    dst_path = os.path.join(UPDATED_ROTATION_PATH, fname)

    if code not in rotation_codes:
        shutil.copy2(src_path, dst_path)
        print(f"  copied {fname} unchanged (code not active)")
        continue

    with open(src_path) as f:
        content = f.read()

    sections = find_sowing_sections(content)
    if not sections:
        print(f"  WARNING: no [sowing:N] section found in {fname}; copying unchanged")
        shutil.copy2(src_path, dst_path)
        continue

    target_num = choose_section_to_update(sections, state_doy)
    if target_num is None:
        print(f"  WARNING: could not determine which sowing section to update in {fname}; copying unchanged")
        shutil.copy2(src_path, dst_path)
        continue

    target = next(s for s in sections if s["num"] == target_num)
    new_section_text = replace_section_dates(target["text"], restart_doy_str)
    new_content = content[:target["start"]] + new_section_text + content[target["end"]:]

    with open(dst_path, "w") as f:
        f.write(new_content)
    print(f"  updated {fname}: [sowing:{target_num}] date -> {restart_doy_str}")
