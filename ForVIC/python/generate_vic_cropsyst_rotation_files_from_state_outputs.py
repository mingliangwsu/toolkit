# Cell 2 — parse vegparam.txt into {cellnum: [veg_code, veg_code, ...]}
# Each cell block is: "cellnum nvegs" header, then nvegs pairs of
# (class-param line, monthly-LAI line). veg_index in the state output
# is the 0-based position of a veg within this ordered list.

def parse_vegparam(path):
    veg_by_cell = {}
    with open(path) as f:
        lines = [ln.rstrip("\n") for ln in f]

    i, n = 0, len(lines)
    while i < n:
        line = lines[i].strip()
        if not line:
            i += 1
            continue
        parts = line.split()
        cellnum, nvegs = int(parts[0]), int(parts[1])
        i += 1
        codes = []
        for _ in range(nvegs):
            veg_line = lines[i].strip().split()
            codes.append(veg_line[0])   # veg class code, e.g. "1401"
            i += 2                      # skip class line + its LAI line
        veg_by_cell[cellnum] = codes
    return veg_by_cell

