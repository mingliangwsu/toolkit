# Cell 4 — map (cellnum, veg_index) -> veg code from vegparam.txt
def lookup_veg_code(row):
    codes = veg_by_cell.get(int(row["cellnum"]))
    if codes is None:
        return None
    idx = int(row["veg_index"])
    return codes[idx] if 0 <= idx < len(codes) else None

